from collections.abc import Iterator
from dataclasses import dataclass
from datetime import datetime
from typing import Protocol
from uuid import UUID

from reply_mcfly.domain.email import (
    IncomingEmail,
    Job,
    MessageMetadata,
    OutboxEntry,
    ReplyDraft,
    Status,
)


@dataclass(frozen=True)
class HistoryPage:
    message_ids: tuple[str, ...]
    history_id: str


class GmailPort(Protocol):
    def history(self, start: str) -> Iterator[HistoryPage]: ...
    def metadata(self, message_id: str) -> MessageMetadata: ...
    def message(self, message_id: str) -> IncomingEmail: ...
    def send(self, job: Job, entry: OutboxEntry) -> str: ...
    def find_sent(self, job: Job, entry: OutboxEntry) -> str | None: ...


class MailboxMaintenancePort(Protocol):
    def profile_history(self) -> str: ...
    def unread_inbox(self) -> tuple[str, ...]: ...
    def renew_watch(self, topic: str) -> datetime: ...


class TaskQueuePort(Protocol):
    def sync(self, mailbox_id: str, event_id: str) -> None: ...
    def process(self, job_id: UUID) -> None: ...


class WorkflowRunner(Protocol):
    def run(self, email: IncomingEmail, timeout: float) -> ReplyDraft: ...


class AttachmentEnricher(Protocol):
    def enrich(self, email: IncomingEmail, timeout: float) -> IncomingEmail: ...


class EmailRepository(Protocol):
    def initialize(self, mailbox_id: str, history_id: str, expiration: datetime | None) -> None: ...
    def watch_expiration(self, mailbox_id: str) -> datetime | None: ...
    def acquire_sync(self, mailbox_id: str, token: UUID) -> str: ...
    def release_sync(self, mailbox_id: str, token: UUID) -> None: ...
    def checkpoint(self, mailbox_id: str, token: UUID, history_id: str) -> None: ...
    def enqueue(self, mailbox_id: str, metadata: MessageMetadata) -> UUID: ...
    def claim(self, job_id: UUID, token: UUID) -> Job: ...
    def get(self, job_id: UUID) -> Job: ...
    def transition(self, job: Job, target: Status, code: str | None = None) -> None: ...
    def prepare(self, job: Job, entry: OutboxEntry) -> None: ...
    def outbox(self, job_id: UUID) -> OutboxEntry | None: ...
    def sent(self, job: Job, gmail_message_id: str) -> None: ...
    def release_lease(self, job: Job) -> None: ...
